/** The meaning to show: French, plus the usual Japanese writing when the app is in Japanese. */
export function meaningFor(word: string, fr: string, ja: boolean): string {
  const g = GLOSS_JA[word];
  return ja && g && g !== word ? `${fr}（${g}）` : fr;
}
